#!/usr/bin/env node
// Install qa-kit's agents as Codex custom agents.
//
// Codex plugins cannot ship agents, so this script converts the Claude agent
// definitions in plugins/qa-kit/agents/*.md into Codex TOML agent files. The
// Markdown files stay the single source of truth.
//
// Usage:
//   node scripts/install-codex-agents.mjs              # into $CODEX_HOME/agents (default ~/.codex/agents)
//   node scripts/install-codex-agents.mjs --project    # into ./.codex/agents of the current directory
//   node scripts/install-codex-agents.mjs --dest DIR   # into DIR
//   node scripts/install-codex-agents.mjs --dry-run    # print what would be written
//   node scripts/install-codex-agents.mjs --uninstall  # remove files this script wrote

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MARKER = '# Generated by qa-kit from plugins/qa-kit/agents. Re-run scripts/install-codex-agents.mjs to update.';

// Claude-only sections: Codex has no agent memory files or team task tools.
const CLAUDE_ONLY_SECTIONS = ['## Memory Maintenance', '## Team Mode'];

// Agents that only report findings run read-only in Codex.
const READ_ONLY_AGENTS = new Set(['code-reviewer']);

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const agentsDir = path.join(repoRoot, 'plugins', 'qa-kit', 'agents');

function parseArgs(argv) {
  const opts = { dest: null, dryRun: false, uninstall: false };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--dry-run') opts.dryRun = true;
    else if (arg === '--uninstall') opts.uninstall = true;
    else if (arg === '--project') opts.dest = path.resolve('.codex', 'agents');
    else if (arg === '--dest') opts.dest = path.resolve(argv[++i] ?? '');
    else if (arg === '-h' || arg === '--help') {
      console.log(fs.readFileSync(fileURLToPath(import.meta.url), 'utf8').split('\n').slice(1, 14).join('\n'));
      process.exit(0);
    } else {
      console.error(`Unknown argument: ${arg}`);
      process.exit(2);
    }
  }
  if (!opts.dest) {
    const codexHome = process.env.CODEX_HOME || path.join(os.homedir(), '.codex');
    opts.dest = path.join(codexHome, 'agents');
  }
  return opts;
}

// Joins a YAML block scalar: `|` keeps line breaks; `>` folds lines into spaces
// but keeps breaks around blank and more-indented lines, as YAML does.
function readBlockScalar(lines, folded) {
  const indents = lines.filter((l) => l.trim()).map((l) => l.match(/^ */)[0].length);
  const dedented = lines.map((l) => l.slice(Math.min(...indents)));
  if (!folded) return dedented.join('\n').trimEnd();
  let out = '';
  let prev = null;
  for (const line of dedented) {
    const keepBreak = prev === null || line === '' || prev === '' || /^\s/.test(line) || /^\s/.test(prev);
    out += prev === null ? line : (keepBreak ? '\n' : ' ') + line;
    prev = line;
  }
  return out.trimEnd();
}

// Reads the top-level frontmatter scalars the agents use: plain, quoted, or block (`>`, `|`).
function parseFrontmatter(source, file) {
  const match = source.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) throw new Error(`${file}: missing YAML frontmatter`);
  const fields = {};
  const lines = match[1].split('\n');
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    if (/^[>|][-+]?$/.test(value)) {
      const block = [];
      while (i + 1 < lines.length && (lines[i + 1].trim() === '' || /^\s/.test(lines[i + 1]))) block.push(lines[++i]);
      value = readBlockScalar(block, value.startsWith('>'));
    } else if (value.startsWith("'") && value.endsWith("'")) value = value.slice(1, -1).replace(/''/g, "'");
    else if (value.startsWith('"') && value.endsWith('"')) value = JSON.parse(value);
    fields[kv[1]] = value;
  }
  return { fields, body: match[2] };
}

// Keeps the "when to use" sentence and drops Claude's <example> transcripts.
function codexDescription(description) {
  return description.split(/\\n|\n|\s*\bExamples?:|\s*<example>/)[0].trim();
}

function stripSections(body) {
  const lines = body.split('\n');
  const kept = [];
  let skipping = false;
  for (const line of lines) {
    if (line.startsWith('## ')) skipping = CLAUDE_ONLY_SECTIONS.some((heading) => line.startsWith(heading));
    if (!skipping) kept.push(line);
  }
  return kept.join('\n').trim() + '\n';
}

// TOML literal strings keep Markdown verbatim; fall back to an escaped basic string.
function tomlMultiline(text) {
  if (!text.includes("'''")) return `'''\n${text}'''`;
  return JSON.stringify(text);
}

function toCodexName(claudeName) {
  return claudeName.replace(/-/g, '_');
}

function renderAgent(file) {
  const { fields, body } = parseFrontmatter(fs.readFileSync(file, 'utf8'), file);
  if (!fields.name || !fields.description) throw new Error(`${file}: name and description are required`);
  const name = toCodexName(fields.name);
  const lines = [
    MARKER,
    `name = ${JSON.stringify(name)}`,
    `description = ${JSON.stringify(codexDescription(fields.description))}`,
  ];
  if (READ_ONLY_AGENTS.has(fields.name)) lines.push('sandbox_mode = "read-only"');
  lines.push(`developer_instructions = ${tomlMultiline(stripSections(body))}`);
  return { name, content: lines.join('\n') + '\n' };
}

function isOurs(target) {
  return fs.readFileSync(target, 'utf8').startsWith(MARKER);
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  const sources = fs.readdirSync(agentsDir).filter((f) => f.endsWith('.md')).sort();
  if (sources.length === 0) throw new Error(`No agents found in ${agentsDir}`);

  let failures = 0;
  for (const source of sources) {
    const agent = renderAgent(path.join(agentsDir, source));
    const target = path.join(opts.dest, `${agent.name}.toml`);
    const exists = fs.existsSync(target);

    if (exists && !isOurs(target)) {
      console.error(`skip   ${target} (exists and was not written by qa-kit)`);
      failures++;
      continue;
    }
    if (opts.uninstall) {
      if (!exists) continue;
      if (!opts.dryRun) fs.rmSync(target);
      console.log(`remove ${target}`);
      continue;
    }
    if (opts.dryRun) {
      console.log(`--- ${target}\n${agent.content}`);
      continue;
    }
    fs.mkdirSync(opts.dest, { recursive: true });
    fs.writeFileSync(target, agent.content);
    console.log(`${exists ? 'update' : 'write '} ${target}`);
  }
  process.exit(failures ? 1 : 0);
}

main();
